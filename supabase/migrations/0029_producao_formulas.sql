-- Fórmulas: o código da fórmula é do sistema de origem (não é o código do produto).
-- product_code = produto que a fórmula fabrica (acabado ou semiacabado), ligado na importação pelo nome e editável.
create table if not exists public.formulas (
  code integer primary key,
  description text not null,
  product_code text references public.products(code) on delete set null,
  min_production_kg numeric,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id)
);
create index if not exists formulas_product_idx on public.formulas (product_code);

-- Insumos da fórmula: quantidade por 1 kg do semiacabado (ou por 1 unidade do acabado).
create table if not exists public.formula_items (
  id uuid primary key default gen_random_uuid(),
  formula_code integer not null references public.formulas(code) on delete cascade,
  seq integer not null default 0,
  input_code text not null,
  input_description text,
  unit text default 'KG',
  qty numeric not null default 0
);
create index if not exists formula_items_formula_idx on public.formula_items (formula_code);

-- Pedido na Produção: Aberto ou Firmado (só o firmado entra no cálculo da aba Produção)
alter table public.order_items add column if not exists pcp_status text not null default 'aberto';
do $$ begin
  alter table public.order_items add constraint order_items_pcp_status_check check (pcp_status in ('aberto', 'firmado'));
exception when duplicate_object then null; end $$;

-- Ordens de produção (botão Em produção da aba Produção)
create table if not exists public.production_orders (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity,
  formula_code integer,
  product_code text,
  description text,
  quantity_kg numeric not null default 0,
  need_kg numeric,
  due_date date,
  item_ids uuid[] not null default '{}',
  status text not null default 'em_producao' check (status in ('em_producao', 'concluida')),
  created_by uuid references public.profiles(id),
  created_by_name text,
  created_at timestamptz not null default now(),
  done_at timestamptz
);

-- Relatório: o que foi enviado para Rotas de entrega pelo botão Pronto: Faturamento
create table if not exists public.production_reports (
  id uuid primary key default gen_random_uuid(),
  order_id uuid references public.orders(id) on delete set null,
  order_number text,
  customer_name text,
  item_ids uuid[] not null default '{}',
  product_code text,
  product_name text,
  quantity_kg numeric,
  delivery_date date,
  details jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id),
  created_by_name text,
  created_at timestamptz not null default now()
);

alter table public.formulas enable row level security;
alter table public.formula_items enable row level security;
alter table public.production_orders enable row level security;
alter table public.production_reports enable row level security;

do $$
declare t text;
begin
  foreach t in array array['formulas', 'formula_items', 'production_orders', 'production_reports'] loop
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('drop policy if exists %I on public.%I', t || '_write', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.is_active())', t || '_select', t);
    execute format('create policy %I on public.%I for all to authenticated using (public.can_write_area(''producao'') or public.can_write_area(''compras'')) with check (public.can_write_area(''producao'') or public.can_write_area(''compras''))', t || '_write', t);
  end loop;
end $$;

-- Aberto/Firmado do item: PCP (produção) ou comercial/faturamento
create or replace function public.set_item_pcp(p_item_ids uuid[], p_status text)
returns int language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if p_status not in ('aberto', 'firmado') then raise exception 'Situação inválida.'; end if;
  if not (public.can_write_area('producao') or public.can_write_area('compras')) then
    raise exception 'Você não tem permissão para mudar esta situação.';
  end if;
  update public.order_items set pcp_status = p_status where id = any(p_item_ids);
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.set_item_pcp(uuid[], text) from public, anon;
grant execute on function public.set_item_pcp(uuid[], text) to authenticated;

-- Estoque por local (1, 2, 5...) da importação vigente + movimentos
create or replace view public.current_stock_locations with (security_invoker = true) as
  with cur as (select id from public.stock_imports where is_current limit 1),
  bal as (
    select b.product_code, b.location, b.quantity as qty
    from public.stock_balances b join cur on cur.id = b.import_id
    union all
    select m.product_code, m.location, m.quantity
    from public.stock_movements m join cur on cur.id = m.import_id
  )
  select bal.product_code as code, bal.location, sum(bal.qty) as quantity
  from bal group by bal.product_code, bal.location;
grant select on public.current_stock_locations to authenticated;
